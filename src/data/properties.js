// Helper functions
export const getFeaturedProperties = () =>
  properties.filter((p) => p.featured);

export const getPropertyBySlug = (slug) =>
  properties.find((p) => p.slug === slug) || null;

export const getPropertiesByType = (type) =>
  properties.filter((p) => p.type === type);

export const getAllSlugs = () =>
  properties.map((p) => ({ slug: p.slug }));

export const filterProperties = ({ type, minPrice, maxPrice, bedrooms, status } = {}) => {
  return properties.filter((p) => {
    if (type      && p.type !== type)               return false;
    if (minPrice  && p.price < minPrice)             return false;
    if (maxPrice  && p.price > maxPrice)             return false;
    if (bedrooms  && p.specs.bedrooms < bedrooms)    return false;
    if (status    && p.status !== status)            return false;
    return true;
  });
};